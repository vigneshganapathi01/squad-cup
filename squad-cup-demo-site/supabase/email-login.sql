-- Squad Cup – team login by email + password (emailed through Brevo). Run AFTER schema.sql. Safe to run again.
-- The password is generated in the database, stored only as a bcrypt hash, and emailed only to the captain's
-- email from the registration form. The browser never sees it. Brevo's API key lives in Supabase Vault.

create extension if not exists pgcrypto with schema extensions;
create extension if not exists pg_net;

-- Secrets are kept out of the teams table so the admin screens never load password hashes.
create table if not exists team_secrets (
  team_id text primary key references teams(id) on delete cascade,
  pass_hash text not null,
  sent_at timestamptz,
  failed_logins int not null default 0,
  locked_until timestamptz
);
create table if not exists team_sessions (
  token text primary key,
  team_id text not null references teams(id) on delete cascade,
  expires_at timestamptz not null
);
create table if not exists email_log (
  id bigint generated by default as identity primary key,
  team_id text references teams(id) on delete cascade,
  to_email text,
  kind text,
  request_id bigint,
  note text,
  at timestamptz not null default now()
);
alter table team_secrets enable row level security;   -- no policies: only the functions below can touch these
alter table team_sessions enable row level security;
alter table email_log enable row level security;
drop policy if exists email_log_staff on email_log;
create policy email_log_staff on email_log for select using (is_staff());

-- 10 characters from an alphabet without look-alikes (no I, l, O, 0, 1).
create or replace function gen_team_password() returns text language sql volatile set search_path = public, extensions as $$
  select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789', (get_byte(b, i) % 55) + 1, 1), '')
  from (select gen_random_bytes(10) b) x, generate_series(0, 9) i
$$;

create or replace function esc_html(t text) returns text language sql immutable as $$
  select replace(replace(replace(coalesce(t, ''), '&', '&amp;'), '<', '&lt;'), '>', '&gt;')
$$;

-- Makes a new password and emails it with the Team ID to the captain. Returns false if email is not set up yet.
create or replace function send_login_email(p_team text, p_kind text) returns boolean language plpgsql security definer set search_path = public, extensions as $$
declare t teams; pw text; key text; s jsonb; sender text; site text; rid bigint; to_email text; html text;
begin
  select * into t from teams where id = p_team;
  if t.id is null then return false; end if;
  to_email := t.players->0->>'email';
  select decrypted_secret into key from vault.decrypted_secrets where name = 'brevo_api_key' limit 1;
  select data into s from settings where id = 1;
  sender := coalesce(s->>'emailFrom', '');
  if key is null or sender = '' then
    insert into email_log (team_id, to_email, kind, note) values (t.id, to_email, p_kind, 'not sent: email not set up');
    return false;
  end if;
  pw := gen_team_password();
  insert into team_secrets (team_id, pass_hash, sent_at) values (t.id, crypt(pw, gen_salt('bf', 8)), now())
    on conflict (team_id) do update set pass_hash = excluded.pass_hash, sent_at = now(), failed_logins = 0, locked_until = null;
  delete from team_sessions where team_id = t.id;   -- old logins stop working
  site := coalesce(nullif(s->>'siteUrl', ''), 'https://squad-cup.vercel.app');
  html := '<div style="font-family:Arial,sans-serif;background:#0d0c08;color:#f6f1e4;padding:28px;border-radius:14px;max-width:520px">'
    || '<h2 style="margin:0 0 6px;color:#f59e0b">' || esc_html(s->>'name') || '</h2>'
    || '<p style="margin:0 0 18px;color:#c9c1aa">' || case when p_kind = 'reset' then 'Here is your new password.' else 'Your team is registered. Keep these details private.' end || '</p>'
    || '<table style="width:100%;border-collapse:collapse;font-size:15px">'
    || '<tr><td style="padding:8px 0;color:#a39d8a">Team</td><td style="padding:8px 0"><b>' || esc_html(t.name) || '</b></td></tr>'
    || '<tr><td style="padding:8px 0;color:#a39d8a">Team ID</td><td style="padding:8px 0"><b>' || t.code || '</b></td></tr>'
    || '<tr><td style="padding:8px 0;color:#a39d8a">Login email</td><td style="padding:8px 0"><b>' || esc_html(to_email) || '</b></td></tr>'
    || '<tr><td style="padding:8px 0;color:#a39d8a">Password</td><td style="padding:8px 0"><b style="font-size:20px;letter-spacing:2px;color:#fde68a">' || pw || '</b></td></tr></table>'
    || '<p style="margin:20px 0"><a href="' || site || '/#/my-team" style="background:#f59e0b;color:#130b00;padding:12px 18px;border-radius:8px;text-decoration:none;font-weight:bold">Open My Team</a></p>'
    || '<p style="font-size:12px;color:#7d745c">Do not share this password. If you did not register, ignore this email.</p></div>';
  select net.http_post(
    url := 'https://api.brevo.com/v3/smtp/email',
    headers := jsonb_build_object('api-key', key, 'Content-Type', 'application/json', 'accept', 'application/json'),
    body := jsonb_build_object(
      'sender', jsonb_build_object('email', sender, 'name', coalesce(nullif(s->>'emailName', ''), s->>'name')),
      'to', jsonb_build_array(jsonb_build_object('email', to_email, 'name', t.players->0->>'name')),
      'subject', s->>'name' || ' login · Team ID ' || t.code,
      'htmlContent', html)
  ) into rid;
  insert into email_log (team_id, to_email, kind, request_id) values (t.id, to_email, p_kind, rid);
  return true;
end $$;

-- Registration (replaces the earlier version): adds a unique captain email and sends the login email.
create or replace function register_team(p jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare s jsonb; pl jsonb; used int; new_id text; t teams; sent boolean; em text;
begin
  select data into s from settings where id = 1;
  if not coalesce((s->>'regOpen')::boolean, false) or exists (select 1 from stages) then raise exception 'Registration is closed'; end if;
  if coalesce(trim(p->>'name'), '') = '' then raise exception 'Team name is required'; end if;
  if length(p->>'name') > 30 then raise exception 'Team name is too long'; end if;
  if coalesce(p->>'logo', '') = '' then raise exception 'Team logo is required'; end if;
  if length(p->>'logo') > 200000 then raise exception 'Team logo is too large'; end if;
  if jsonb_array_length(p->'players') <> 4 then raise exception '4 players are required'; end if;
  if exists (select 1 from teams where lower(name) = lower(trim(p->>'name')) and status not in ('rejected', 'withdrawn')) then raise exception 'Team name already taken'; end if;
  for pl in select * from jsonb_array_elements(p->'players') loop
    if coalesce(trim(pl->>'name'), '') = '' then raise exception 'Every player needs a name'; end if;
    if (pl->>'mobile') !~ '^[6-9][0-9]{9}$' then raise exception 'Mobile % is not valid', pl->>'mobile'; end if;
    if (pl->>'email') !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Email % is not valid', pl->>'email'; end if;
    if (pl->>'uid') !~ '^[0-9]{8,12}$' then raise exception 'UID % is not valid', pl->>'uid'; end if;
    if exists (select 1 from teams tt, jsonb_array_elements(tt.players) x where tt.status not in ('rejected', 'withdrawn') and x->>'uid' = pl->>'uid') then raise exception 'UID % is already in another team', pl->>'uid'; end if;
    if exists (select 1 from teams tt, jsonb_array_elements(tt.players) x where tt.status not in ('rejected', 'withdrawn') and x->>'mobile' = pl->>'mobile') then raise exception 'Mobile % is already in another team', pl->>'mobile'; end if;
  end loop;
  if (select count(distinct x->>'uid') from jsonb_array_elements(p->'players') x) < 4 then raise exception 'Same UID used twice in this team'; end if;
  if (select count(distinct x->>'mobile') from jsonb_array_elements(p->'players') x) < 4 then raise exception 'Same mobile used twice in this team'; end if;
  em := lower(trim(p->'players'->0->>'email'));
  if exists (select 1 from teams where status not in ('rejected', 'withdrawn') and lower(players->0->>'email') = em) then raise exception 'The captain email % is already used by another team', em; end if;

  perform pg_advisory_xact_lock(42);  -- one registration at a time so slots never double-book
  select count(*) into used from teams where entry = 'SLOT' and status in ('pending', 'approved');
  new_id := 't' || replace(gen_random_uuid()::text, '-', '');
  insert into teams (id, name, logo, entry, slot_no, status, source, players, captain_mobile)
  values (new_id, trim(p->>'name'), p->>'logo', 'SLOT',
    case when used < (s->>'slots')::int then (select min(n) from generate_series(1, (s->>'slots')::int) n
      where n not in (select slot_no from teams where entry = 'SLOT' and status in ('pending', 'approved') and slot_no is not null)) end,
    case when used < (s->>'slots')::int then 'pending' else 'waitlist' end,
    'form', p->'players', p->'players'->0->>'mobile')
  returning * into t;
  insert into audit_log (who, action, what) values ('public', 'Team registered', t.code || ' ' || t.name);
  sent := send_login_email(t.id, 'register');
  return jsonb_build_object('id', t.id, 'code', t.code, 'name', t.name, 'logo', t.logo, 'status', t.status, 'slotNo', t.slot_no, 'entry', t.entry,
    'emailed', sent, 'emailTo', regexp_replace(em, '^(.{2}).*(@.*)$', '\1•••\2'));
end $$;

-- Login: captain email + password → a 30-day session token. Never raises, so failed tries are counted.
create or replace function team_login(p_email text, p_password text) returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare t teams; sec team_secrets; tok text;
begin
  select * into t from teams where lower(players->0->>'email') = lower(trim(p_email)) and status not in ('rejected', 'withdrawn') order by created_at desc limit 1;
  if t.id is null then return jsonb_build_object('error', 'Email or password is wrong.'); end if;
  select * into sec from team_secrets where team_id = t.id;
  if sec.team_id is null then return jsonb_build_object('error', 'Your password has not been sent yet. Use “Email me a new password”.'); end if;
  if sec.locked_until > now() then return jsonb_build_object('error', 'Too many wrong tries. Try again in 15 minutes.'); end if;
  if sec.pass_hash <> crypt(coalesce(p_password, ''), sec.pass_hash) then
    update team_secrets set failed_logins = failed_logins + 1,
      locked_until = case when failed_logins + 1 >= 5 then now() + interval '15 minutes' end where team_id = t.id;
    return jsonb_build_object('error', 'Email or password is wrong.');
  end if;
  update team_secrets set failed_logins = 0, locked_until = null where team_id = t.id;
  delete from team_sessions where expires_at < now();
  tok := encode(gen_random_bytes(24), 'hex');
  insert into team_sessions (token, team_id, expires_at) values (tok, t.id, now() + interval '30 days');
  return jsonb_build_object('token', tok, 'code', t.code);
end $$;

create or replace function team_logout(p_token text) returns boolean language sql security definer set search_path = public as $$
  delete from team_sessions where token = p_token returning true
$$;

-- Forgot password: always the same answer, so it can't be used to find out who registered.
create or replace function team_reset_password(p_email text) returns text language plpgsql security definer set search_path = public as $$
declare t teams; last timestamptz;
begin
  select * into t from teams where lower(players->0->>'email') = lower(trim(p_email)) and status not in ('rejected', 'withdrawn') order by created_at desc limit 1;
  if t.id is not null then
    select sent_at into last from team_secrets where team_id = t.id;
    if last is null or last < now() - interval '10 minutes' then perform send_login_email(t.id, 'reset'); end if;
  end if;
  return 'If that email belongs to a team captain, a new password is on its way. Check spam too.';
end $$;

create or replace function session_team(p_token text) returns text language sql stable security definer set search_path = public as $$
  select team_id from team_sessions where token = p_token and expires_at > now()
$$;

-- Team dashboard, check-in and complaints now use the session token.
drop function if exists team_dashboard(text, text);
drop function if exists team_checkin(text, text, text);
drop function if exists raise_complaint(text, text, text, text, text, text);

create or replace function team_dashboard(p_token text) returns jsonb language plpgsql security definer set search_path = public as $$
declare t teams;
begin
  select * into t from teams where id = session_team(p_token);
  if t.id is null then return null; end if;
  return jsonb_build_object(
    'team', to_jsonb(t),
    'checkins', coalesce((select jsonb_agg(match_id) from checkins where team_id = t.id), '[]'),
    'rooms', coalesce((select jsonb_agg(jsonb_build_object('matchId', r.match_id, 'roomId', r.room_id, 'roomPass', r.room_pass))
      from match_rooms r join matches m on m.id = r.match_id join checkins c on c.match_id = r.match_id and c.team_id = t.id
      where m.status in ('room', 'live')), '[]'),
    'complaints', coalesce((select jsonb_agg(to_jsonb(c) order by c.at desc) from complaints c where c.team_id = t.id), '[]'),
    'notifications', coalesce((select jsonb_agg(to_jsonb(n) order by n.at desc) from (select * from notifications where team_id = t.id order by at desc limit 30) n), '[]'),
    'links', coalesce((select jsonb_agg(jsonb_build_object('key', l.key, 'link', l.link)) from group_links l
      where l.link is not null and l.key in (select s.id || '|' || (g->>'label') from stages s, jsonb_array_elements(s.data->'groups') g where (g->'teamIds') ? t.id)), '[]'));
end $$;

create or replace function team_checkin(p_token text, p_match text) returns boolean language plpgsql security definer set search_path = public as $$
declare t teams; st jsonb;
begin
  select * into t from teams where id = session_team(p_token) and status = 'approved';
  if t.id is null then raise exception 'Please log in again'; end if;
  if not exists (select 1 from matches where id = p_match and status in ('checkin', 'room')) then raise exception 'Check-in is not open'; end if;
  select s.data into st from stages s join matches m on m.stage_id = s.id where m.id = p_match;
  if not exists (select 1 from jsonb_array_elements(st->'groups') g, jsonb_array_elements(g->'matches') mm
                 where mm->>'id' = p_match and (g->'teamIds') ? t.id) then raise exception 'Your team is not in this match'; end if;
  insert into checkins (match_id, team_id) values (p_match, t.id) on conflict do nothing;
  return true;
end $$;

create or replace function raise_complaint(p_token text, p_match text, p_label text, p_reason text, p_shot text) returns boolean language plpgsql security definer set search_path = public as $$
declare t teams;
begin
  select * into t from teams where id = session_team(p_token);
  if t.id is null then raise exception 'Please log in again'; end if;
  if coalesce(trim(p_reason), '') = '' then raise exception 'Please write what is wrong'; end if;
  insert into complaints (team_id, match_id, match_label, reason, shot) values (t.id, p_match, p_label, left(p_reason, 1000), left(p_shot, 200));
  insert into audit_log (who, action, what) values ('team', 'Complaint raised', t.name);
  return true;
end $$;

-- Admin: email logins (for Wild Cards, CSV imports or anyone who lost theirs) and see what was sent.
create or replace function admin_send_logins(p_team_ids text[]) returns int language plpgsql security definer set search_path = public as $$
declare id text; n int := 0;
begin
  if not is_admin() then raise exception 'Admins only'; end if;
  foreach id in array p_team_ids loop
    if send_login_email(id, 'admin') then n := n + 1; end if;
  end loop;
  return n;
end $$;

create or replace function admin_login_status() returns table (team_id text, sent_at timestamptz) language sql security definer set search_path = public as $$
  select s.team_id, s.sent_at from team_secrets s where is_staff()
$$;

create or replace function admin_email_log() returns table (at timestamptz, team_id text, to_email text, kind text, status int, note text) language sql security definer set search_path = public as $$
  select l.at, l.team_id, l.to_email, l.kind, r.status_code, coalesce(l.note, case when r.status_code >= 300 then left(r.content, 200) end)
  from email_log l left join net._http_response r on r.id = l.request_id
  where is_staff() order by l.at desc limit 200
$$;

-- Admin reset also clears logins.
create or replace function admin_reset() returns boolean language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Admins only'; end if;
  delete from team_sessions; delete from team_secrets; delete from email_log;
  delete from notifications; delete from group_links; delete from checkins; delete from match_rooms; delete from matches; delete from stages; delete from complaints; delete from teams;
  perform setval('team_code_seq', 1, false);
  return true;
end $$;

-- Who may call what. Supabase gives new functions to everyone by default, so close the internal ones.
revoke all on function gen_team_password(), send_login_email(text, text), session_team(text), esc_html(text) from public, anon, authenticated;
revoke all on function register_team(jsonb), team_login(text, text), team_logout(text), team_reset_password(text),
  team_dashboard(text), team_checkin(text, text), raise_complaint(text, text, text, text, text),
  admin_send_logins(text[]), admin_login_status(), admin_email_log(), admin_reset() from public, anon, authenticated;
grant execute on function register_team(jsonb), team_login(text, text), team_logout(text), team_reset_password(text),
  team_dashboard(text), team_checkin(text, text), raise_complaint(text, text, text, text, text) to anon, authenticated;
grant execute on function admin_send_logins(text[]), admin_login_status(), admin_email_log(), admin_reset() to authenticated;
