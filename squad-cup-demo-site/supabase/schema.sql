-- Squad Cup – Supabase schema. Paste into Supabase → SQL Editor → Run (safe to run again).
-- Public visitors can: read settings, stages, matches and team names/logos; register; open their own team.
-- Staff (rows in public.staff) can do everything else. Room passwords and players' contact details stay private.

create sequence if not exists team_code_seq;

create table if not exists settings (
  id int primary key default 1 check (id = 1),
  data jsonb not null default '{"name":"Squad Cup","slots":252,"wildCards":6,"regOpen":true,"regCloses":"2026-12-20"}'
);
insert into settings (id) values (1) on conflict do nothing;

create table if not exists staff (
  user_id uuid primary key,
  role text not null check (role in ('admin', 'room')),
  name text
);

create table if not exists teams (
  id text primary key,
  code text unique not null default ('FF-' || lpad(nextval('team_code_seq')::text, 4, '0')),
  name text not null,
  logo text,
  entry text not null check (entry in ('SLOT', 'WC')),
  slot_no int,
  status text not null check (status in ('pending', 'approved', 'rejected', 'waitlist', 'withdrawn')),
  reason text,
  source text,
  players jsonb not null,
  captain_mobile text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists teams_name_active on teams (lower(name)) where status not in ('rejected', 'withdrawn');

create table if not exists stages (id int primary key, data jsonb not null);

create table if not exists matches (
  id text primary key,
  stage_id int not null references stages(id) on delete cascade,
  status text not null default 'scheduled',
  results jsonb,
  result_status text not null default 'none',
  screenshots jsonb not null default '[]'
);

create table if not exists match_rooms (
  match_id text primary key references matches(id) on delete cascade,
  room_id text,
  room_pass text
);

create table if not exists checkins (
  match_id text references matches(id) on delete cascade,
  team_id text references teams(id) on delete cascade,
  at timestamptz not null default now(),
  primary key (match_id, team_id)
);

create table if not exists complaints (
  id bigint generated by default as identity primary key,
  team_id text references teams(id) on delete cascade,
  match_id text,
  match_label text,
  reason text not null,
  shot text,
  status text not null default 'open',
  answer text,
  at timestamptz not null default now()
);

create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  who text, action text, what text
);

-- WhatsApp hybrid: captain messages and admin-made group invite links (staff only; teams see their own through team_dashboard).
create table if not exists notifications (
  id text primary key,
  key text unique not null,
  team_id text references teams(id) on delete cascade,
  type text not null,
  text text not null,
  status text not null default 'queued',
  at timestamptz not null default now(),
  sent_at timestamptz
);
create table if not exists group_links (
  key text primary key,          -- "<stage index>|<group label>"
  link text,
  invites jsonb not null default '{}'
);

-- Public team list: no mobiles, emails, UIDs or Team IDs.
create or replace view public_teams as
  select id, name, logo, entry, slot_no, status from teams;

